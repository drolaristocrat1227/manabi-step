  const PQ = (q, a, w, e, h) => ({ q, a, w, e, h });
  function readingGen(passages, hint) {
    let order = [], cur = null, qi = 0;
    return function () {
      if (!cur || qi >= cur.qs.length) {
        if (!order.length) order = shuffle(passages.map((_, i) => i));
        cur = passages[order.pop()]; qi = 0;
      }
      const it = cur.qs[qi++], opts = shuffle([it.a].concat(it.w));
      const box = `<div class="passage"><div class="ptitle">${cur.title}</div>${cur.body.map((p) => `<p${/^[「【]/.test(p) ? ' class="ni"' : ''}>${p}</p>`).join('')}</div>`;
      const stem = `<div class="pq">問${qi}　${it.q}</div>`;
      return { q: box + stem, passage: cur.title, stem, choices: opts, correct: opts.indexOf(it.a), hints: [hint[0], it.h || hint[1]], explain: it.e || `答えは「${it.a}」。` };
    };
  }

